// State/quality checks on the dashboard's real presentation module.
import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
import ts from "typescript";
const source=await readFile(new URL("../src/sinvert/presentation.ts",import.meta.url),"utf8");
const code=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {summary,groupState,number,explainBlocker}=await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const group=(index,power,configured=true)=>({index,configured,consent:true,state_code:2,measurement_quality:"plc_reported",active_messages:[],measurements:{active_power:power}});
const data=groups=>({diagnostics:{data_freshness:"fresh",communication_state:"online",sinvert:{groups,on_blockers:[],power_blockers:[]}}});
const real=data([group(1,50),group(2,25),group(3,999,false),group(4,999,false)]);
assert.equal(summary(real,false).power,75);
assert.equal(summary(real,false).configured.length,2);
assert.equal(summary(real,true).power,null);
const stale=structuredClone(real);stale.diagnostics.data_freshness="stale";
assert.equal(summary(stale,false).power,null);
const offline=structuredClone(real);offline.diagnostics.communication_state="offline";
assert.equal(summary(offline,false).power,null);
const partial=structuredClone(real);partial.diagnostics.sinvert.groups[1].measurement_quality="communication_flags";
assert.equal(summary(partial,false).power,null);
const missing=structuredClone(real);missing.diagnostics.sinvert.groups[0].measurements.active_power=null;
assert.equal(summary(missing,false).power,null);
const nonfinite=structuredClone(real);nonfinite.diagnostics.sinvert.groups[0].measurements.active_power=NaN;
assert.equal(summary(nonfinite,false).power,null);
assert.equal(summary(data([]),false).power,null);
assert.equal(summary(data([group(1,0)]),false).power,0);
assert.equal(summary(null,false).fresh,false);
const warning=group(1,0);warning.state_code=4;
assert.equal(groupState(warning,true).label,"Allarmi presenti");
assert.equal(groupState(warning,false).tone,"muted");
warning.measurement_quality="communication_flags";
assert.equal(groupState(warning,true).label,"Feedback da verificare");
warning.configured=false;
assert.equal(groupState(warning,true).label,"Non configurato");
const unknown=group(1,0);unknown.state_code=99;
assert.equal(groupState(unknown,true).label,"Stato non riconosciuto");
assert.equal(number(null),"—");assert.equal(number(NaN),"—");assert.equal(number(1000),"1.000");
assert.ok(!explainBlocker("Nessun consenso M55 attivo: arresto ciclico PLC").includes("M55"));
console.log("20 state, measurement quality and operator wording checks passed");
