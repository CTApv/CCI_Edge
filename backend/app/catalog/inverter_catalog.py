def trio_telemetry_point(
    key: str,
    label: str,
    register_type: str,
    data_address: int,
    length: int,
    datatype: str,
    *,
    scale: float = 1.0,
    unit: str = "",
    section: str,
    summary_metric: str | None = None,
    visible: bool = True,
    enum_map: dict[int, str] | None = None,
    bitmask_labels: dict[int, str] | None = None,
) -> InverterPoint:
    protocol_meta: dict[str, str | int | float | bool] = {"section": section}
    if summary_metric is not None:
        protocol_meta["summary_metric"] = summary_metric
    if enum_map is not None:
        protocol_meta["enum_map"] = enum_map
    if bitmask_labels is not None:
        protocol_meta["bitmask_labels"] = bitmask_labels

    return telemetry_point(
        key=key,
        label=label,
        register_type=register_type,
        address=data_address - 1,
        length=length,
        datatype=datatype,
        scale=scale,
        unit=unit,
        visible=visible,
        protocol_meta=protocol_meta,
    )


def trio_command_point(
    key: str,
    label: str,
    data_address: int,
    datatype: str,
    *,
    scale: float = 1.0,
    unit: str = "",
    section: str,
    min_value: float | None = None,
    max_value: float | None = None,
    step: float | None = None,
) -> InverterPoint:
    protocol_meta: dict[str, str | int | float | bool] = {"section": section}
    if min_value is not None:
        protocol_meta["min_value"] = min_value
    if max_value is not None:
        protocol_meta["max_value"] = max_value
    if step is not None:
        protocol_meta["step"] = step

    return command_point(
        key=key,
        label=label,
        register_type="holding",
        address=data_address - 1,
        length=2 if datatype in {"uint32", "int32", "float32", "sf32"} else 1,
        datatype=datatype,
        scale=scale,
        unit=unit,
        protocol_meta=protocol_meta,
    )


